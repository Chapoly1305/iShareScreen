"""Structural contract for decoder implementations; recovery stays backend-specific."""
from __future__ import annotations

from typing import Protocol

from .tiles import TileFrame


class Decoder(Protocol):
    num_tiles: int

    def set_params(self, vps: bytes, sps: bytes, all_pps: dict[int, bytes]) -> None: ...
    def start(self) -> None: ...
    def feed_burst(self, tile_nalu_cache: dict[int, list[bytes]]) -> None: ...
    def feed_nalu(self, nalu: bytes, tile_idx: int, donl: int | None = None) -> None: ...
    def get_frame(self, tile_idx: int) -> TileFrame | None: ...
    def consume_fir_request(self) -> list[int]: ...
    def restart(self) -> None: ...
    def close(self) -> None: ...
